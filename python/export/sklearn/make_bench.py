import os

from sklearn import tree
import sklearn.datasets as datasets
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, OneHotEncoder
from sklearn.compose import ColumnTransformer

from export_sklearn_data.find_interesting_vectors import find_vectors
from dt_explanation import write_dttxt_file

def process_bunch(data, target, dt, name, n_features, accf):
    """
    Train a DT based on the provided Bunch object and write a DTTXT file.

    The file is created in a directory "bench/" and named after the "name"
    parameter. A line will be appended in the (opened) file accf to report
    the accuracy of the trained DT.
    """

    X_train, X_test, y_train, y_test = train_test_split(data, target, random_state=0)

    dt = dt.fit(X_train, y_train)
    acc = dt.score(X_test, y_test)

    vs = find_vectors(dt, n_features)

    f = "./bench/" + name + ".txt"

    write_dttxt_file(dt, vs, data_filename=f)

    accf.write(name + "\t" + str(acc) + "\n")

def main():
    """
    Generate benchmarks for the evaluation of the DT explainer as a collection
    of DTTXT files.

    Each generated file contains the representation for a DT trained on one of
    the "Real World" Scikit-learn datasets, and vectors generated by exploring
    the paths in the DT. A file "accuracy.txt" reports the accuracy for each
    trained DT. The generated files are put in a directory "bench/".
    """

    os.makedirs("./bench/", exist_ok=True)

    with open("./bench/accuracy.txt", "w") as accf:
        kddcup99_categorical_features = ['protocol_type', 'service', 'flag', 'land', 'logged_in', 'is_host_login', 'is_guest_login']
        kddcup99_preprocessor = ColumnTransformer(transformers=[('cat', OneHotEncoder(handle_unknown='ignore'), kddcup99_categorical_features)], remainder='passthrough', verbose_feature_names_out=False)
        le = LabelEncoder()

        X_digits, y_digits = datasets.load_digits(return_X_y=True)
        dt_digits = tree.DecisionTreeClassifier(random_state=0)
        process_bunch(X_digits, y_digits, dt_digits, "digits", len(X_digits[0]), accf)

        X_covtype, y_covtype = datasets.fetch_covtype(return_X_y=True)
        dt_covtype = tree.DecisionTreeClassifier(random_state=0)
        process_bunch(X_covtype, y_covtype, dt_covtype, "covtype", len(X_covtype[0]), accf)

        X_olivetti, y_olivetti = datasets.fetch_olivetti_faces(return_X_y=True)
        dt_olivetti = tree.DecisionTreeClassifier(random_state=0)
        process_bunch(X_olivetti, y_olivetti, dt_olivetti, "olivetti", len(X_olivetti[0]), accf)

        lfw_pairs = datasets.fetch_lfw_pairs()
        X_lfw_pairs = lfw_pairs['data']
        y_lfw_pairs = lfw_pairs['target']
        dt_lfw_pairs = tree.DecisionTreeClassifier(random_state=0)
        process_bunch(X_lfw_pairs, y_lfw_pairs, dt_lfw_pairs, "lfw_pairs", len(X_lfw_pairs[0]), accf)

        X_kddcup99, y_kddcup99 = datasets.fetch_kddcup99(return_X_y=True, as_frame=True)
        X_kddcup99 = kddcup99_preprocessor.fit_transform(X_kddcup99)
        y_kddcup99 = le.fit_transform(y_kddcup99)
        dt_kddcup99 = tree.DecisionTreeClassifier(random_state=0)
        process_bunch(X_kddcup99, y_kddcup99, dt_kddcup99, "kddcup99", X_kddcup99.shape[1], accf)

if __name__ == "__main__":
    main()

